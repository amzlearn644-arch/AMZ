#!/usr/bin/env python3
"""Export the local AMZ SQLite catalog into a D1-compatible SQL file.

API bearer tokens are intentionally omitted. Re-enter provider credentials
as Cloudflare secrets or through a protected admin workflow after migration.
"""
from __future__ import annotations
import argparse
import sqlite3
from pathlib import Path

def literal(value):
    if value is None:
        return "NULL"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--db", default="../data/amz.sqlite3", help="Path to local AMZ SQLite database")
    parser.add_argument("--out", default="import_catalog.sql", help="Output SQL file")
    args = parser.parse_args()
    db_path = Path(args.db).resolve()
    out_path = Path(args.out).resolve()
    if not db_path.is_file():
        raise SystemExit(f"Database not found: {db_path}")
    conn = sqlite3.connect(f"file:{db_path.as_posix()}?mode=ro", uri=True)
    conn.row_factory = sqlite3.Row
    statements = ["-- Generated by export_sqlite_to_sql.py; review before applying."]
    tables = {
        "software": ["slug","name","summary","description","category","os","version","icon_url","homepage_url","download_url","source","source_id","updated_at"],
        "api_sources": ["name","url","records_path","mapping","pagination"],
        "sync_state": ["provider","last_attempt","last_success","status","message"],
    }
    for table, columns in tables.items():
        try:
            rows = conn.execute(f"SELECT {','.join(columns)} FROM {table}").fetchall()
        except sqlite3.OperationalError:
            continue
        for row in rows:
            values = [row[column] for column in columns]
            if table == "api_sources":
                # Never export local API credentials into a generated SQL file.
                names = columns[:1] + ["url","token"] + columns[2:]
                values = [row["name"], row["url"], ""] + [row[c] for c in columns[2:]]
                statements.append(
                    f"INSERT INTO api_sources ({','.join(names)}) VALUES ({','.join(literal(v) for v in values)});"
                )
            else:
                statements.append(
                    f"INSERT OR REPLACE INTO {table} ({','.join(columns)}) VALUES ({','.join(literal(v) for v in values)});"
                )
    conn.close()
    out_path.write_text("\n".join(statements) + "\n", encoding="utf-8")
    print(f"Exported SQL to {out_path}")

if __name__ == "__main__":
    main()
